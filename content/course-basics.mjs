const TATWEEL = "ـ";

/** Position table for one letter: alone, initial, middle, final. */
function forms(letter, joining) {
  return joining
    ? [letter, letter + TATWEEL, TATWEEL + letter + TATWEEL, TATWEEL + letter]
    : [letter, letter, TATWEEL + letter, TATWEEL + letter];
}

/** Letter with the three short vowels and sukun. */
function vowelled(letter) {
  return [letter + "َ", letter + "ِ", letter + "ُ", letter + "ْ"];
}

function lettersTable(letters) {
  return {
    block_type: "table",
    title: "Формы букв в слове",
    body: {
      header: true,
      rows: [
        ["Буква", "Отдельно", "В начале", "В середине", "В конце", "С огласовками"],
        ...letters.map((l) => [l.name, ...forms(l.char, l.joining), vowelled(l.char).join(" ")]),
      ],
    },
  };
}

function sifatBlock(letters) {
  return {
    block_type: "sifat",
    title: "",
    body: { text: letters.map((l) => `${l.name} (${l.char}): ${l.sifat}.`).join("\n\n") },
  };
}

function makhrajBlock(letters) {
  return {
    block_type: "makhraj",
    title: "",
    body: { text: letters.map((l) => `${l.name} (${l.char}): ${l.makhraj}.`).join("\n\n") },
  };
}

